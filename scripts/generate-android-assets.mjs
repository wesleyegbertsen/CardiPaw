// Generates the Android launcher icon resources from public/favicon.svg, the same source
// as the PWA icons (npm run generate-pwa-assets), so the two can't drift apart.
// Usage:  npm run generate-android-assets                          (writes the files)
//         node scripts/generate-android-assets.mjs --check         (exit 1 if the XML is stale)
// --check compares only the XML: PNG bytes depend on the sharp/libvips version, so the
// legacy PNGs aren't checked; regenerate them whenever favicon.svg changes.
// The paw's placement (SCALE, OFFSET) assumes favicon.svg's single <path> and its
// <g transform>; the script stops if either changes, rather than misplace the paw.

import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const RES = join(ROOT, 'android', 'app', 'src', 'main', 'res');
const SOURCE = 'public/favicon.svg';

function extract(svg, pattern, what) {
  const match = svg.match(pattern);
  if (!match) throw new Error(`${SOURCE}: no ${what} found (pattern ${pattern})`);
  return match[1];
}

const svg = readFileSync(join(ROOT, SOURCE), 'utf8');
const tileColor = extract(svg, /<rect[^>]*fill="(#[0-9a-fA-F]{6})"/, '<rect fill="#rrggbb">');
const pawPath = extract(svg, /<path d="([^"]+)"/, '<path d>');

// The adaptive icon draws only this one path, placed by SCALE and OFFSET below, so a
// second shape would be missing from it and a new transform would place the paw
// differently in the favicon (and the legacy PNGs) than in the adaptive icon.
const pathCount = svg.match(/<path\b/g).length;
if (pathCount !== 1) {
  throw new Error(
    `${SOURCE} has ${pathCount} <path> elements; this script draws exactly one. ` +
      'Update the foreground template (and SCALE, OFFSET) in scripts/generate-android-assets.mjs.',
  );
}
const EXPECTED_TRANSFORM = 'translate(8, 8) scale(0.094)';
const transform = extract(svg, /<g transform="([^"]+)"/, '<g transform>');
if (transform !== EXPECTED_TRANSFORM) {
  throw new Error(
    `${SOURCE}: <g transform="${transform}">, expected "${EXPECTED_TRANSFORM}". ` +
      'Recompute SCALE and OFFSET in scripts/generate-android-assets.mjs for the new ' +
      'placement, then update EXPECTED_TRANSFORM.',
  );
}

// The paw path is drawn in a 512-unit box (Font Awesome); its bounding box is
// (0,32)-(512,480), so its centre is (256,256). An adaptive icon is a 108dp canvas whose
// centre 66dp circle always stays visible. Scaling to 48dp wide (48/512) and moving by
// (108-48)/2 = 30 centres the paw, with every point within 26dp of the centre.
const SCALE = 48 / 512;
const OFFSET = (108 - 48) / 2;
const HEADER = `<!-- Generated by scripts/generate-android-assets.mjs from ${SOURCE}. Do not edit. -->`;

// VectorDrawable groups scale (about pivot 0,0) before they translate: the same as the
// SVG transform "translate(30 30) scale(0.09375)".
const foreground = `<?xml version="1.0" encoding="utf-8"?>
${HEADER}
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="${OFFSET}"
        android:translateY="${OFFSET}"
        android:scaleX="${SCALE}"
        android:scaleY="${SCALE}">
        <path
            android:fillColor="#FFFFFF"
            android:pathData="${pawPath}" />
    </group>
</vector>
`;

// <monochrome> (Android 13 themed icons) uses only the alpha channel, so the white
// foreground serves as is. Launchers before API 33 ignore the element.
const adaptiveIcon = `<?xml version="1.0" encoding="utf-8"?>
${HEADER}
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
`;

const launcherBackground = `<?xml version="1.0" encoding="utf-8"?>
${HEADER}
<resources>
    <color name="ic_launcher_background">${tileColor}</color>
</resources>
`;

const xmlFiles = {
  'drawable/ic_launcher_foreground.xml': foreground,
  'mipmap-anydpi-v26/ic_launcher.xml': adaptiveIcon,
  'mipmap-anydpi-v26/ic_launcher_round.xml': adaptiveIcon,
  'values/ic_launcher_background.xml': launcherBackground,
};

if (process.argv.includes('--check')) {
  const stale = Object.entries(xmlFiles)
    .filter(([path, content]) => {
      let onDisk;
      try {
        onDisk = readFileSync(join(RES, path), 'utf8');
      } catch (err) {
        if (err.code === 'ENOENT') return true;
        throw err;
      }
      // Git may check the files out with CRLF (core.autocrlf on Windows).
      return onDisk.replace(/\r\n/g, '\n') !== content;
    })
    .map(([path]) => path);
  if (stale.length) {
    console.error(`Out of date with ${SOURCE}: ${stale.join(', ')}`);
    console.error('Run `npm run generate-android-assets` and commit the result.');
    process.exit(1);
  }
  console.log('Android icon resources are up to date.');
} else {
  for (const [path, content] of Object.entries(xmlFiles)) {
    mkdirSync(dirname(join(RES, path)), { recursive: true });
    writeFileSync(join(RES, path), content);
  }

  // Launcher icons for API 24–25, which predate adaptive icons: 48dp at each density.
  // ic_launcher is the favicon (rounded tile); ic_launcher_round is the adaptive icon
  // through a circular mask (its 72dp visible area, 18dp in from each edge).
  const { default: sharp } = await import('sharp'); // loaded here so --check needs no native module
  const roundSvg = (px) =>
    `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="18 18 72 72">` +
    `<circle cx="54" cy="54" r="36" fill="${tileColor}"/>` +
    `<path transform="translate(${OFFSET} ${OFFSET}) scale(${SCALE})" fill="#fff" d="${pawPath}"/>` +
    `</svg>`;
  const DENSITIES = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
  for (const [density, px] of Object.entries(DENSITIES)) {
    const dir = join(RES, `mipmap-${density}`);
    mkdirSync(dir, { recursive: true });
    // favicon.svg is 64 units square; sharp renders SVG at 72 dpi = 1 px per unit.
    await sharp(Buffer.from(svg), { density: (72 * px) / 64 })
      .resize(px, px)
      .png({ compressionLevel: 9 })
      .toFile(join(dir, 'ic_launcher.png'));
    await sharp(Buffer.from(roundSvg(px)))
      .png({ compressionLevel: 9 })
      .toFile(join(dir, 'ic_launcher_round.png'));
  }
  const pngCount = Object.keys(DENSITIES).length * 2;
  console.log(`Wrote ${Object.keys(xmlFiles).length} XML files and ${pngCount} PNGs under ${RES}`);
}
